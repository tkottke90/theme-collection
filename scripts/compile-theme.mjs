import { execSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

/**
 * Compiles a theme's shared Tailwind `@theme {}` tokens (themes/<name>/theme.css)
 * together with a package's own component source (so Tailwind's utility-class
 * content scan picks up classes used in that package) into one real stylesheet,
 * via the Tailwind CLI. `@theme {}` is Tailwind-dialect syntax a plain browser
 * or bundler can't interpret on its own, so this has to run through Tailwind
 * before the result is usable by non-Tailwind build steps (esbuild/Jest/Vite).
 */
function compile({ themeDir, contentGlobs, extraCss = "" }) {
  const absThemeFile = resolve(process.cwd(), themeDir, "theme.css");
  const absContentGlobs = contentGlobs.map((glob) => resolve(process.cwd(), glob));

  // The temp entry file must live inside the calling package's own tree
  // (not the OS tmpdir) so Tailwind's own `@import "tailwindcss"` module
  // resolution — which walks up from the entry file's location — can find
  // the calling package's `tailwindcss` devDependency.
  const tmpDir = mkdtempSync(resolve(process.cwd(), ".compile-theme-tmp-"));
  const entryFile = join(tmpDir, "entry.css");
  const outFile = join(tmpDir, "out.css");

  const entry = [
    `@import "tailwindcss";`,
    `@import "${absThemeFile}";`,
    ...absContentGlobs.map((glob) => `@source "${glob}";`),
    extraCss,
  ].join("\n");

  writeFileSync(entryFile, entry);

  try {
    execSync(`tailwindcss -i "${entryFile}" -o "${outFile}" --minify`, { stdio: "inherit" });
    return readFileSync(outFile, "utf8");
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

/** Compiles the theme + content into a real `.css` file at `outFile`. */
export function compileThemeFile({ themeDir, contentGlobs, outFile, extraCss = "" }) {
  const css = compile({ themeDir, contentGlobs, extraCss });
  const absOutFile = resolve(process.cwd(), outFile);
  mkdirSync(dirname(absOutFile), { recursive: true });
  writeFileSync(absOutFile, css);
}

/**
 * Shared "bar" shimmer treatment for skeleton-loading placeholders — pure
 * CSS (a keyframe animation + a utility class) that Tailwind has no utility
 * for, so it's injected as `extraCss` by any package that needs it rather
 * than duplicated by hand per package. Relies on each theme's
 * `--color-skeleton-base`/`--color-skeleton-highlight` tokens.
 */
export const SKELETON_SHIMMER_CSS = `
.theme-shimmer {
  background-image: linear-gradient(
    90deg,
    var(--color-skeleton-base) 25%,
    var(--color-skeleton-highlight) 37%,
    var(--color-skeleton-base) 63%
  );
  background-size: 400px 100%;
  animation: theme-skeleton-shimmer 1.4s ease-in-out infinite;
}
@keyframes theme-skeleton-shimmer {
  0% {
    background-position: -200px 0;
  }
  100% {
    background-position: 200px 0;
  }
}
@media (prefers-reduced-motion: reduce) {
  .theme-shimmer {
    animation: none;
  }
}
`;

/**
 * Tailwind v4 gives its `--tw-*` variables (border style, `::before` content,
 * ...) their defaults via `@property`, which browsers ignore inside shadow
 * roots. Its fallback block is wrapped in an `@supports` guard that only
 * matches browsers *without* `@property`, so modern browsers get neither and
 * `border` / `before:` utilities silently render nothing in a component.
 * Dropping the guard makes the defaults always apply; they stay in the
 * lowest-priority `properties` layer, so utilities still override them.
 *
 * Only needed for shadow-DOM output (`compileThemeModule`) — a page-level
 * stylesheet gets the `@property` defaults normally.
 */
export function unguardPropertyDefaults(css) {
  const out = css.replace(
    /@layer properties\{@supports [^{]*\{([^{}]*\{[^{}]*\})\}\}/,
    "@layer properties{$1}",
  );
  if (out === css && css.includes("@layer properties")) {
    throw new Error(
      "compile-theme: Tailwind's @layer properties fallback block has an unexpected shape",
    );
  }
  return out;
}

function escapeForTemplateLiteral(css) {
  return css.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

/**
 * Compiles the theme + content and writes a generated TypeScript module
 * exporting it as a Lit `unsafeCSS(...)` CSSResult, for packages (e.g. Web
 * Components) that need the compiled stylesheet embedded in JS rather than
 * delivered as a standalone file — Shadow DOM can't be reached by a
 * page-level stylesheet, only by styles attached inside the shadow root.
 */
export function compileThemeModule({ themeDir, contentGlobs, outFile, extraCss = "" }) {
  const css = unguardPropertyDefaults(compile({ themeDir, contentGlobs, extraCss }));
  const absOutFile = resolve(process.cwd(), outFile);
  mkdirSync(dirname(absOutFile), { recursive: true });
  const module = `// AUTO-GENERATED by scripts/compile-theme.mjs — do not edit by hand.
import { unsafeCSS } from "lit";

export const themeStyles = unsafeCSS(\`${escapeForTemplateLiteral(css)}\`);
`;
  writeFileSync(absOutFile, module);
}
